import assert from 'node:assert/strict'
import { mkdirSync } from 'node:fs'
import { chromium } from 'playwright-core'

const origin = process.env.SIM_URL ?? 'http://localhost:4173/'
const out = new URL('../screens/', import.meta.url).pathname
mkdirSync(out, { recursive: true })
const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER ?? '/usr/bin/brave' })
const errors = []
const check = (ok, message) => { assert.ok(ok, message); console.log(`ok   ${message}`) }
const open = async (url, width = 1440, colorScheme = 'light') => {
  const page = await browser.newPage({ viewport: { width, height: 1000 }, colorScheme })
  page.on('pageerror', (e) => errors.push(String(e)))
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()) })
  await page.goto(url, { waitUntil: 'networkidle' })
  await page.waitForSelector('.vdot-view')
  return page
}
try {
  if (process.env.EXPECT_DEFAULT_TAB === 'vdot') {
    const root = await open(origin)
    check(await root.getByTestId('vdot-apr').innerText() === '5.33%', 'the separate subdomain opens the vDOT preview by default')
    await root.close()
  }
  const page = await open(`${origin}#t=vdot`)
  check(await page.getByTestId('vdot-apr').innerText() === '5.33%', 'default theoretical carry matches the model')
  const rateInput = page.getByLabel('DOT borrow APR', { exact: true })
  const curveToggle = page.getByLabel('Use DOT reserve curve', { exact: true })
  check(await curveToggle.isChecked() && await rateInput.isDisabled(), 'DOT interest uses the reserve curve by default')
  await curveToggle.uncheck()
  await rateInput.fill('3')
  await rateInput.blur()
  check(Number.parseFloat(await page.getByTestId('vdot-apr').innerText()) < 5.33 && (await page.locator('[aria-label="vDOT carry results"]').innerText()).includes('manual rate'), 'a higher manual DOT rate reduces carry and is labeled')
  await rateInput.fill('0')
  await rateInput.blur()
  check(Number.parseFloat(await page.getByTestId('vdot-apr').innerText()) > 5.33, 'a zero DOT borrow rate is accepted')
  await curveToggle.check()
  check(await rateInput.isDisabled() && await page.getByTestId('vdot-apr').innerText() === '5.33%', 'switching back to the curve restores automatic pricing')
  check(await page.getByLabel('Loop target HF', { exact: true }).inputValue() === '1.01' && await page.getByRole('button', { name: '69% fee', exact: true }).getAttribute('aria-pressed') === 'true', 'default HF is 1.01 and the fee is 69%')
  check(await page.getByLabel('Main interest discount', { exact: true }).count() === 0 && (await page.locator('.strategy-intro').innerText()).includes('Original vault collateral → borrow DOT'), 'the default funding path borrows DOT directly and has no HOLLAR discount control')
  check((await page.getByTestId('vdot-status').innerText()).includes('91.09%') && (await page.getByTestId('vdot-status').innerText()).includes('1.0824'), 'the default target shows the borrowing LTV constraint')
  check((await page.getByTestId('vdot-status').innerText()).includes('5.0 bps'), 'the direct DOT funding quote replaces the HOLLAR quote')
  check(await page.getByTestId('vdot-shock-pnl').innerText() === '0.00%', 'DOT funding matches the source principal through a common DOT-price shock')
  check(await page.getByTestId('vdot-shock-hf').innerText() === '1.010×', 'common DOT fall leaves loop HF unchanged')
  check((await page.locator('.vdot-risk').innerText()).includes('market trading discounts leave the loop’s oracle HF unchanged'), 'oracle HF is distinguished from market execution prices')
  await page.getByRole('button', { name: '+50% DOT', exact: true }).click()
  check(await page.getByTestId('vdot-main-hf').innerText() === '0.756×' && await page.getByTestId('vdot-shock-hf').innerText() === '1.010×' && (await page.locator('.vdot-risk').innerText()).includes('vault liquidatable'), 'DOT appreciation can liquidate the vault while the correlated loop HF stays unchanged')
  await page.getByRole('button', { name: '−30% DOT', exact: true }).click()
  await page.getByRole('button', { name: '22% fee', exact: true }).click()
  check(await page.getByTestId('vdot-apr').innerText() === '15.63%', 'fee comparison updates carry')
  await curveToggle.uncheck()
  await rateInput.fill('3')
  await rateInput.blur()
  await page.locator('summary').filter({ hasText: /^Oracle stress$/ }).click()
  await page.getByLabel('Oracle conversion-rate change', { exact: true }).fill('-15')
  await page.getByLabel('Oracle conversion-rate change', { exact: true }).blur()
  const shockedHf = Number.parseFloat(await page.getByTestId('vdot-shock-hf').innerText())
  check(Math.abs(shockedHf - 0.8585) < 0.00051 && (await page.locator('[aria-label="vDOT price shock results"]').innerText()).includes('liquidatable'), 'a conversion-rate feed decline shows its effect on liquidation')
  const carry = await page.getByTestId('vdot-apr').innerText()
  await page.getByLabel('DOT / USD price move', { exact: true }).fill('50')
  await page.getByLabel('DOT / USD price move', { exact: true }).blur()
  check(await page.getByTestId('vdot-apr').innerText() === carry, 'price shocks are not added to carry APR')
  await page.waitForTimeout(800)
  const url = page.url()
  check(new URL(url).hash.includes('vd=vd4.'), 'vDOT settings receive their own versioned share token')
  const back = await open(url)
  check(await back.locator('[aria-label="vDOT carry results"]').innerText() === await page.locator('[aria-label="vDOT carry results"]').innerText(), 'vDOT share link restores the results')
  check(await back.getByLabel('DOT / USD price move', { exact: true }).inputValue() === '50', 'share link restores the stress scenario')
  check(await back.getByLabel('DOT borrow APR', { exact: true }).inputValue() === '3' && !(await back.getByLabel('Use DOT reserve curve', { exact: true }).isChecked()), 'share link preserves the manual DOT rate')
  await back.getByRole('button', { name: 'Two strategies', exact: true }).click()
  check(await back.getByTestId('strategy-apr').innerText() === '6.78%', 'original strategy defaults remain unchanged')
  await back.getByRole('button', { name: 'vDOT / DOT', exact: true }).click()
  check(await back.getByTestId('vdot-apr').innerText() === carry, 'vDOT assumptions survive switching tabs')
  await back.close()
  await page.getByLabel('Loop target HF', { exact: true }).fill('1.05')
  await page.getByLabel('Loop target HF', { exact: true }).blur()
  check((await page.getByTestId('vdot-status').innerText()).includes('fails market'), 'HF target above allowed borrowing LTV is blocked')
  await page.getByRole('button', { name: 'reset vDOT assumptions', exact: true }).click()
  check(await curveToggle.isChecked() && await rateInput.isDisabled(), 'reset restores the default reserve-curve mode')
  await page.getByLabel('DOT eMode', { exact: true }).uncheck()
  await page.getByLabel('Loop target HF', { exact: true }).fill('1.25')
  await page.getByLabel('Loop target HF', { exact: true }).blur()
  check((await page.getByTestId('vdot-status').innerText()).includes('Market checks pass'), 'standard mode uses its own borrowing limits')
  await curveToggle.uncheck()
  await rateInput.fill('3')
  await rateInput.blur()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'export vDOT results', exact: true }).click()
  const stream = await (await download).createReadStream()
  let text = ''
  for await (const chunk of stream) text += chunk
  const json = JSON.parse(text)
  check(json.params.dotBorrowApr === 0.03 && json.result.dotBorrowRate === 0.03 && json.result.dotMarketBorrowRate !== 0.03, 'export records both the manual rate and the reserve-curve comparison')
  check(json.params.useEMode === false && json.snapshot.block === '16706517' && json.quotes.quotes.length === 5 && json.params.fundingAsset === 'DOT' && json.params.mainDiscount === 0 && json.funding.crossRpcMatches && json.oracle.crossRpcMatches && json.oracle.current.sameDotUsdSource, 'export includes mode, raw snapshot, routing and oracle evidence')
  await page.getByRole('button', { name: 'reset vDOT assumptions', exact: true }).click()
  await page.screenshot({ path: `${out}vdot-light.png`, fullPage: true })
  const mobile = await open(url, 390)
  check(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile layout stays within the viewport')
  await mobile.screenshot({ path: `${out}vdot-mobile.png`, fullPage: true })
  await mobile.close()
  const dark = await open(url, 1440, 'dark')
  await dark.screenshot({ path: `${out}vdot-dark.png`, fullPage: true })
  await dark.close()
  const invalid = await open(`${origin}#t=vdot&vd=vd5.broken`)
  check((await invalid.locator('.main > .banner').innerText()).includes('could not read vDOT settings'), 'malformed vDOT links show a visible error')
  check(await invalid.getByTestId('vdot-apr').innerText() === '5.33%', 'malformed links restore pinned defaults')
  await invalid.close()
  const legacy = await open(`${origin}#t=vdot&vd=vd3.e30`)
  check(await legacy.getByTestId('vdot-apr').innerText() === '4.86%' && await legacy.getByTestId('vdot-shock-pnl').innerText() === '−22.50%' && await legacy.getByLabel('Main interest discount', { exact: true }).count() === 1, 'older links preserve HOLLAR funding and its economics')
  await legacy.close()
  check(errors.length === 0, `no browser errors (${errors.join(' | ')})`)
} finally {
  await browser.close()
}
